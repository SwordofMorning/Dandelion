##
 # @file src/subagent/pool.py
 # @date 2026/08/07
 # 
 # @brief Control all subagent.py
 # Held by MyAgent; creates SubAgents, assigns IDs, mounts toolsets and turns
 # every failure into a structured SubAgentResult.
 #
 # @note The pool is the last, non-bypassable depth gate: whatever a tool or a
 #       model asks for, depth must satisfy 1 <= depth <= max_depth.
 #

import time
import uuid
from src.runtime import Runtime
from .subagent import SubAgent
from .result import SubAgentResult
from .registry import resolve_toolset

##
 # @brief Subagent Pool.
 #
class SubAgentPool:
    ##
     # @brief Constructor.
     #
     # @param safe_client llm_request client.
     # @param logger log management.
     # @param config environment config.
     # @param all_tools all tools, used to resolve toolset to subagents.
     # @param max_depth max SubAgent depth ([Main] SUB_DEPTH; 0 disables).
     #
    def __init__(self, safe_client, logger, config, all_tools, max_depth=1, runtime=None):
        self.safe_client = safe_client
        self.logger = logger
        self.config = config
        self.all_tools = all_tools
        self.runtime = runtime if runtime is not None else Runtime()
        try:
            self.max_depth = max(int(max_depth), 0)
        except (TypeError, ValueError):
            self.max_depth = 0
        # End-try
    # End-def

    ##
     # @brief Build a failed result without running anything.
     #
    @staticmethod
    def _failed(subagent_id, task_description, depth, summary, err_msg, start_time):
        return SubAgentResult(
            subagent_id=subagent_id,
            task_description=task_description,
            status="failed",
            summary=summary,
            depth_reached=depth if isinstance(depth, int) else 0,
            duration_seconds=round(time.time() - start_time, 3),
            error_message=err_msg,
        )
    # End-def

    ##
     # @brief Create and run a SubAgent in one call.
     #
     # Flow: 
     # 1. assign a sa-<hex> id -> 
     # 2. depth gate (disabled / out of range -> "failed" result) ->
     # 3. resolve toolset (failure -> "failed" result) -> 
     # 4. construct SubAgent (failure -> "failed" result) ->
     # 5. SubAgent.run() (exception -> "failed" result collecting sub_results) -> 
     # 6. return.
     #
     # @note Called by SpawnSubagentTool (depth=1, no parent_tools) and
     # RestrictedSpawnTool (depth+1, parent_tools = parent's toolset),
     # both in src/tool/agent/spawn_tool.py.
     #
     # @param role_prompt SubAgent's system prompt, generated by the parent's plan tool.
     # @param toolset_name Toolset name resolved via TOOLSET_REGISTRY.
     # @param task_description SubAgent's task text.
     # @param depth Depth of the SubAgent to create (direct child of root = 1).
     # @param parent_tools Parent's toolset; restricts the resolved toolset.
     #
     # @return SubAgentResult.
     #
    def create_and_run(
        self,
        role_prompt: str,
        toolset_name: str,
        task_description: str,
        depth: int = 1,
        parent_tools: set = None
    ) -> SubAgentResult:
        start_time = time.time()
        subagent_id = f"sa-{uuid.uuid4().hex[:8]}"

        # Depth gate.
        if self.max_depth <= 0:
            return self._failed(subagent_id, task_description, depth,
                                "SubAgents are disabled.",
                                "SubAgent spawn blocked: SUB_DEPTH is 0.", start_time)
        # End-if
        if not isinstance(depth, int) or isinstance(depth, bool) or depth < 1 or depth > self.max_depth:
            return self._failed(subagent_id, task_description, depth,
                                "SubAgent spawn blocked.",
                                f"SubAgent spawn blocked: depth {depth!r} is outside 1..{self.max_depth} "
                                f"(SUB_DEPTH={self.max_depth}). Complete the task yourself.",
                                start_time)
        # End-if

        # Tool Error
        try:
            tools = resolve_toolset(toolset_name, self.all_tools, parent_tools)
        except ValueError as e:
            err_msg = f"{e!s}"
            self.logger.log_api_call(f"SUBAGENT:{subagent_id} INIT ERROR", {"error": err_msg})
            return self._failed(subagent_id, task_description, depth,
                                "Failed to initialize SubAgent. Invalid toolset.", err_msg, start_time)
        # End-except

        subagent = None
        try:
            subagent = SubAgent(
                safe_client=self.safe_client,
                logger=self.logger,
                config=self.config,
                pool=self,
                role_prompt=role_prompt,
                tools=tools,
                depth=depth,
                max_depth=self.max_depth,
                subagent_id=subagent_id,
                runtime=self.runtime,
                routing_context={
                    "task_description": task_description,
                    "toolset_name": toolset_name,
                    "depth": depth,
                }
            )
            return subagent.run(task_description)
        except Exception as e:
            phase = "execution" if subagent is not None else "construction"
            err_msg = f"Unexpected error during {phase}: {e!s}"
            self.logger.log_api_call(f"SUBAGENT:{subagent_id} EXEC ERROR", {"error": err_msg})
            result = self._failed(subagent_id, task_description, depth,
                                  "SubAgent execution crashed.", err_msg, start_time)
            if subagent is not None:
                result.sub_results = list(subagent.sub_results)
                result.artifacts = list(subagent.artifacts)
                result.depth_reached = max([depth] + [r.depth_reached for r in subagent.sub_results])
            # End-if
            return result
        # End-try
    # End-def
# End-class
